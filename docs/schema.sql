CREATE SEQUENCE SEQ_CL_CHAT_ROOMS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CL_CHAT_MESSAGES START WITH 1 INCREMENT BY 1 NOCACHE;

